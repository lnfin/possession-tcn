"""Sub-step A6 of P10: agreement of infer.predict under H <-> A and the mirror in y.

    python -m analysis.clean.equiv --work DIR --weights DIR

T1 copies of the 9 matches are regenerated by seed. A swap exchanges the teams on the arrays and H, A in
the output; the mirror flips y. The threshold of A6 is the minimum over the matches minus 25 %.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from analysis.clean import bank, grid, metric, pod
from mtah import infer


def agreement(players, ball, slot_team, period, t0, pitch, model):
    base = infer.predict(players, ball, slot_team, period, t0, pitch, model)
    other = np.where(slot_team >= 0, 1 - slot_team, slot_team).astype(np.int8)
    sw = infer.predict(players, ball, other, period, t0, pitch, model)
    sw = np.where(sw == "H", "A", np.where(sw == "A", "H", sw))
    Q, B = players.copy(), ball.copy()
    Q[..., 1] = pitch[1] - Q[..., 1]
    B[:, 1] = pitch[1] - B[:, 1]
    mi = infer.predict(Q, B, slot_team, period, t0, pitch, model)
    rot = infer.predict(_rotate(players, pitch), _rotate(ball, pitch), slot_team, period, t0, pitch, model)
    ok = period > 0
    return (float((base == sw)[ok].mean()), float((base == mi)[ok].mean()), float((base == rot)[ok].mean()))


def _rotate(x, pitch):
    out = x.copy()
    out[..., 0] = pitch[0] - x[..., 0]
    out[..., 1] = pitch[1] - x[..., 1]
    return out


def _job(args):
    work, name, s, weights, fallback = args
    root = str(Path(work) / "bank")
    ref = bank.load_refs(root, name)
    game = metric.load_game(name)
    Pm, team, Bm, _, period, _, _ = bank.make_copy(name, 2, s, game, ref["Y"], ref["log"], fallback)
    t0 = {p: a for p, a, _ in grid.periods_of(period)}
    r = agreement(Pm, Bm, team, period, t0, game["pitch_m"], infer.load_model(weights))
    return name, s, r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", required=True)
    ap.add_argument("--weights", required=True)
    a = ap.parse_args()
    state = json.loads((Path(a.work) / "state.json").read_text())
    jobs = [(a.work, n, s, a.weights, state.get("fallback", False)) for n in metric.GAMES_EVAL for s in (0, 1)]
    with grid.pool(pod.cpu_quota()) as p:
        res = list(p.imap_unordered(_job, jobs))
    by = {}
    for n, _, r in res:
        by.setdefault(n, []).append(r)
    means = np.array([np.mean(v, axis=0) for v in by.values()])
    out = {"swap": float(means[:, 0].min() * 0.75), "mirror": float(means[:, 1].min() * 0.75),
           "rotation_min": float(means[:, 2].min()), "by_match": {k: np.mean(v, axis=0).tolist() for k, v in by.items()}}
    state["a6"] = out
    (Path(a.work) / "state.json").write_text(json.dumps(state, indent=1, default=float))
    print(json.dumps(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
